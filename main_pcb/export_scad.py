#!/usr/bin/env python3
"""Writes board.scad: the main board as data for the bass's case, read back from KiCad:
outline, screw holes, and every part's body as a box on the top (courtyard rectangle,
height by package). Board frame as design.py (X from the side wall's edge, Y up, seen
from the parts). ../bass/elec.scad includes it.
usage: export_scad.py [main_pcb.kicad_pcb]"""
import sys, os, pcbnew
import design as d

BOARD = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "main_pcb.kicad_pcb")
OX, OY = 100.0, 100.0
b = pcbnew.LoadBoard(BOARD)
def W(x, y): return (round(pcbnew.ToMM(x) - OX, 3), round(OY - pcbnew.ToMM(y), 3))
# body heights above the board's top [datasheet maxima where known;]
HEIGHT = {"ESP32-S3-WROOM-1": 3.25, "USB_C_Receptacle_GCT_USB4105": 3.31, "VQFN-32": 1.0,
          "VQFN-16": 1.0, "Texas_DRC0010J": 1.0, "SOT-23-5": 1.45, "SOT-23-6": 1.45, "SOT-23": 1.12,
          "R_0402": 0.4, "C_0402": 0.55, "L_0402": 0.55, "C_0603": 0.95, "C_0805": 1.35, "Fuse_1206": 1.2,
          "L_1008": 1.2, "LTST-S326": 1.6, "SOT-523": 0.8, "TestPoint": 0.05}
def height(fpid):
    for k, h in HEIGHT.items():
        if k in fpid: return h
    raise SystemExit("no height for " + fpid)

parts = []
for f in b.GetFootprints():
    fp = f.GetFPIDAsString(); ref = f.GetReference()
    if ref == "U1":                # the module's body, not its courtyard (which carries the antenna's keepout)
        x, y = W(f.GetPosition().x, f.GetPosition().y)
        x0, y0, x1, y1 = x - 9, y - 12.75, x + 9, y + 12.75
    else:
        q = f.GetCourtyard(pcbnew.F_CrtYd).BBox()
        x0, y1 = W(q.GetLeft(), q.GetTop()); x1, y0 = W(q.GetRight(), q.GetBottom())
    if ref == "D1":                # the LED's body: from its lens (0.75 inside the courtyard) to its pads' end
        px = [W(bb.GetLeft(), bb.GetTop()) for p in f.Pads() for bb in [p.GetBoundingBox()]] + \
             [W(bb.GetRight(), bb.GetBottom()) for p in f.Pads() for bb in [p.GetBoundingBox()]]
        x0 += 0.75; x1 = max(q[0] for q in px); y0 = min(q[1] for q in px); y1 = max(q[1] for q in px)
    parts.append((ref, round(x0, 3), round(y0, 3), round(x1, 3), round(y1, 3), height(fp)))
parts.sort()

out = os.path.join(os.path.dirname(os.path.abspath(BOARD)), "board.scad")
L = ["// The bass's main board: generated by export_scad.py from main_pcb.kicad_pcb; do not edit",
     "// board frame: X from the side wall's edge of the board, Y up, seen from the parts; W up from the top face",
     f"main_w = {d.W}; main_h = {d.H}; main_t = {d.PCB_T};",
     f"main_holes = {[list(p) for p in d.HOLES]};",
     f"main_hole_d = {d.HOLE_D}; main_head_d = {d.HEAD_D};",
     f"main_jack_y = {d.JACK_Y};          // the earphone jack's axis (Y), over the board",
     f"main_led_y = {[c['pos'][1] for c in d.C if c['ref'] == 'D1'][0]};           // the charge light's lens (Y), at the edge",
     "// [ref, X0, Y0, X1, Y1, height]",
     "main_parts = [", ",\n".join(f'  ["{r}", {x0}, {y0}, {x1}, {y1}, {h}]' for r, x0, y0, x1, y1, h in parts), "];",
     ""]
open(out, "w").write("\n".join(L))
print(out, len(parts), "parts")
