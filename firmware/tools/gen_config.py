#!/usr/bin/env python3
"""Writes the firmware's generated sources from its configuration:

    python3 gen_config.py OUT_DIR

reads  ../config/eziach.toml             settings and the MIDI channel per key
       ../config/<map_name>               push/pull tones per key (from ../ctrl)
       ../../hall_pcb/discant/channels.json, ../../hall_pcb/bass/channels.json
                                          which ADC channel reads which key
writes OUT_DIR/keymap.h, keymap.c         one entry per key: board, row, key, bus, ADC
                                          address, AIN, MIDI channel, push and pull tones
       OUT_DIR/config.h                   the settings as #defines

Fails if a key of the table has no ADC channel or the other way round, or if two keys share
one. Board 0 is the discant on I2C bus 1, board 1 the bass on bus 2 (../main_pcb/spec.md).
"""
import json, os, sys, tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
CONFIG = os.path.join(HERE, "..", "config")
BOARDS = [("discant", 1), ("bass", 2)]     # board name, I2C bus
MAX_NOTES = 3                              # notes per key (../ctrl MAPPING_MAX_KEYS)


def fl(x):
    """a C float literal: 2190 -> 2190.0f"""
    s = repr(float(x))
    return s + "f"


NAMES = ["C", "Cis", "D", "Es", "E", "F", "Fis", "G", "Gis", "A", "B", "H"]


def chord_root(notes):
    """The major chord the tones belong to: the root whose triad (root, third, fifth) is
    complete among them and covers most of them (a dominant's seventh counts too)."""
    pcs = [n % 12 for n in notes]
    best, score = None, -1
    for r in range(12):
        if not all((r + i) % 12 in pcs for i in (0, 4, 7)):
            continue
        s = sum(1 for p in pcs if (p - r) % 12 in (0, 4, 7, 10))
        if s > score:
            best, score = r, s
    return best


def notes(v):
    v = v if isinstance(v, list) else [v]
    assert 1 <= len(v) <= MAX_NOTES and all(0 <= n <= 127 for n in v), v
    return v


def main(out):
    conf = tomllib.load(open(os.path.join(CONFIG, "eziach.toml"), "rb"))
    m = conf["mapping"]
    table = tomllib.load(open(os.path.join(CONFIG, m["map_name"]), "rb"))
    push, pull, chan, mirror = table["map_push"], table["map_pull"], m["map_channels"], m["mirror"]

    third = conf["tuning"]["third_cents"]

    def tuned(v, root):
        """cents per tone: the chord's third low, the rest as tempered"""
        return [third if root is not None and (n - root) % 12 == 4 else 0.0 for n in v]

    keys = []
    report = []
    for b, (name, bus) in enumerate(BOARDS):
        channels = json.load(open(os.path.join(HERE, "..", "..", "hall_pcb", name, "channels.json")))
        on_board = {}
        for addr, ains in channels.items():
            for ain, rk in ains.items():
                pos = (rk["row"], rk["key"])
                assert pos not in on_board, "%s: two channels for row %d key %d" % (name, *pos)
                on_board[pos] = (int(addr.rstrip("h"), 16), int(ain[3:]))
        rows = push[b]
        assert len(rows) == len(pull[b]) == len(chan[b]), name
        seen = set()
        for r, row in enumerate(rows):
            assert len(row) == len(pull[b][r]) == len(chan[b][r]), (name, r)
            n = len(row)
            # the discant: one chord per row and direction; the bass: each chord on its own
            roots = {}
            if b == 0:
                for d, tab in (("push", row), ("pull", pull[b][r])):
                    roots[d] = chord_root([x for x in tab if not isinstance(x, list)])
                    report.append("%s row %d %s: %s" % (name, r, d, NAMES[roots[d]] if roots[d] is not None else "-"))
            for c in range(n):
                k = (n - c) if mirror[b] else (c + 1)          # the board's key number
                assert (r, k) in on_board, "%s: row %d key %d of the table is not on the board" % (name, r, k)
                addr, ain = on_board[(r, k)]
                ps, pl = notes(row[c]), notes(pull[b][r][c])
                if b == 0:
                    pc, lc = tuned(ps, roots["push"]), tuned(pl, roots["pull"])
                else:     # a bass chord's own root; a single bass note is a root itself
                    pc = tuned(ps, chord_root(ps)) if len(ps) > 1 else [0.0]
                    lc = tuned(pl, chord_root(pl)) if len(pl) > 1 else [0.0]
                keys.append(dict(board=b, row=r, key=k, bus=bus, addr=addr, ain=ain, channel=chan[b][r][c],
                                 push=ps, pull=pl, push_cents=pc, pull_cents=lc))
                seen.add((r, k))
        missing = set(on_board) - seen
        assert not missing, "%s: board keys without a tone: %s" % (name, sorted(missing))

    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "keymap.h"), "w") as f:
        f.write("""// generated by tools/gen_config.py from config/ and ../hall_pcb/*/channels.json - do not edit
#ifndef KEYMAP_H
#define KEYMAP_H
#include <stdint.h>

#define KEYMAP_NUM_KEYS %d
#define KEYMAP_NUM_BOARDS %d
#define KEYMAP_MAX_NOTES %d
#define KEYMAP_ADDR_BASE 0x10   // ADS7128 addresses 10h..
#define KEYMAP_NUM_ADDR 8
#define KEYMAP_NUM_AIN 8

typedef struct keymap_key_t {
	uint8_t board;     // 0 discant (I2C bus 1), 1 bass (bus 2)
	uint8_t row;       // as the board: row 0 at the front
	uint8_t key;       // 1.. along the row, key 1 at the lowest X
	uint8_t bus;       // I2C bus 1 or 2
	uint8_t addr;      // ADS7128 address
	uint8_t ain;       // its input 0..7
	uint8_t channel;   // MIDI channel
	uint8_t n_push, push[KEYMAP_MAX_NOTES];   // tones on push (MIDI note numbers)
	uint8_t n_pull, pull[KEYMAP_MAX_NOTES];   // tones on pull
	float push_cents[KEYMAP_MAX_NOTES];       // each tone's tuning against tempered (thirds low)
	float pull_cents[KEYMAP_MAX_NOTES];
} keymap_key_t;

extern const keymap_key_t keymap_keys[KEYMAP_NUM_KEYS];
// key index by board, address - KEYMAP_ADDR_BASE and AIN; -1: no key there
extern const int8_t keymap_by_channel[KEYMAP_NUM_BOARDS][KEYMAP_NUM_ADDR][KEYMAP_NUM_AIN];
// ADCs per board: their addresses, and how many
extern const uint8_t keymap_adc_addr[KEYMAP_NUM_BOARDS][KEYMAP_NUM_ADDR];
extern const uint8_t keymap_num_adc[KEYMAP_NUM_BOARDS];

#endif
""" % (len(keys), len(BOARDS), MAX_NOTES))

    by = [[[-1] * 8 for _ in range(8)] for _ in BOARDS]
    for i, k in enumerate(keys):
        by[k["board"]][k["addr"] - 0x10][k["ain"]] = i
    adcs = [sorted({k["addr"] for k in keys if k["board"] == b}) for b in range(len(BOARDS))]

    def arr(v):
        v = v + [0] * (MAX_NOTES - len(v))
        return "{" + ", ".join(map(str, v)) + "}"

    def farr(v):
        v = v + [0.0] * (MAX_NOTES - len(v))
        return "{" + ", ".join(fl(x) for x in v) + "}"

    with open(os.path.join(out, "keymap.c"), "w") as f:
        f.write("// generated by tools/gen_config.py - do not edit\n#include \"keymap.h\"\n\n")
        f.write("const keymap_key_t keymap_keys[KEYMAP_NUM_KEYS] = {\n")
        for k in keys:
            f.write("\t{%d, %d, %2d, %d, 0x%02X, %d, %d, %d, %s, %d, %s, %s, %s},\n" % (
                k["board"], k["row"], k["key"], k["bus"], k["addr"], k["ain"], k["channel"],
                len(k["push"]), arr(k["push"]), len(k["pull"]), arr(k["pull"]),
                farr(k["push_cents"]), farr(k["pull_cents"])))
        f.write("};\n\nconst int8_t keymap_by_channel[KEYMAP_NUM_BOARDS][KEYMAP_NUM_ADDR][KEYMAP_NUM_AIN] = {\n")
        for b in by:
            f.write("\t{\n" + "".join("\t\t{%s},\n" % ", ".join("%2d" % x for x in a) for a in b) + "\t},\n")
        f.write("};\n\nconst uint8_t keymap_adc_addr[KEYMAP_NUM_BOARDS][KEYMAP_NUM_ADDR] = {\n")
        for a in adcs:
            f.write("\t{%s},\n" % ", ".join("0x%02X" % x for x in a + [0] * (8 - len(a))))
        f.write("};\n\nconst uint8_t keymap_num_adc[KEYMAP_NUM_BOARDS] = {%s};\n" % ", ".join(str(len(a)) for a in adcs))

    ml, fo, ke, sy = conf["main_loop"], conf["force"], conf["keys"], conf["synthesizer"]
    qk = ml["quit_keys"]
    qidx = []
    for b, r, k in qk:
        hit = [i for i, x in enumerate(keys) if (x["board"], x["row"], x["key"]) == (b, r, k)]
        assert hit, "quit key %s is not a key" % [b, r, k]
        qidx.append(hit[0])
    vols = sy["channel_volumes"]
    with open(os.path.join(out, "config.h"), "w") as f:
        f.write("""// generated by tools/gen_config.py from config/eziach.toml - do not edit
#ifndef CONFIG_H
#define CONFIG_H

#define CONF_NUM_QUIT_KEYS %d
#define CONF_QUIT_KEYS {%s}            // key indices into keymap_keys
#define CONF_TRANSPOSE_ROW %d          // discant row that sets the transposition
#define CONF_TRANSPOSE %d
#define CONF_NEW_FORCE_PORTION %s
#define CONF_VELOCITY %d

#define CONF_FORCE_COUNTS_PER_NEWTON %s
#define CONF_FORCE_THRESHOLD %s
#define CONF_FORCE_OFFSET %s
#define CONF_FORCE_PUSH_GAIN %s
#define CONF_FORCE_PULL_GAIN %s
#define CONF_FORCE_SIGN %d

#define CONF_KEY_ACTUATE %s
#define CONF_KEY_RELEASE %s
#define CONF_KEY_DEFAULT_SPAN %d
#define CONF_KEY_REST_FOLLOW %s

#define CONF_SOUNDFONT_NAME "%s"
#define CONF_NUM_CHANNELS %d
#define CONF_CHANNEL_VOLUMES {%s}
#define CONF_SAMPLE_RATE %d
#define CONF_PERIOD_SIZE %d
#define CONF_SYNTH_GAIN_DB %s
#define CONF_THIRD_CENTS %s

#endif
""" % (len(qidx), ", ".join(map(str, qidx)), ml["transpose_row"], ml["transpose"], fl(ml["new_force_portion"]),
       ml["velocity"], fl(fo["counts_per_newton"]), fl(fo["threshold"]), fl(fo["offset"]), fl(fo["push_gain"]),
       fl(fo["pull_gain"]), fo["sign"], fl(ke["actuate"]), fl(ke["release"]), ke["default_span"], fl(ke["rest_follow"]),
       sy["soundfont_name"],
       len(vols), ", ".join(fl(v) for v in vols), sy["sample_rate"], sy["period_size"], fl(sy["gain_db"]), fl(conf["tuning"]["third_cents"])))
    lowered = sum(1 for k in keys for c in k["push_cents"] + k["pull_cents"] if c)
    print("gen_config: chords " + "; ".join(report) + "; %d tones as thirds at %+g cents" % (lowered, third))
    print("gen_config: %d keys (%s)" % (len(keys), ", ".join(
        "%s %d" % (n, sum(1 for k in keys if k["board"] == b)) for b, (n, _) in enumerate(BOARDS))))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/gen")
