#!/usr/bin/env node
// channel.js: solve a route and write the slot that carries its cable as an
// OpenSCAD polyhedron, to be cut out of a housing.
//   node channel.js [routes.json] name
// The route's "channel": {width, thick, out}: slot cross-section (mm) swept
// along the cable from inside the connector to the end of its tail, and the
// .scad file to write (relative to routes.json). The file defines
// module <name>() { polyhedron(...) }.
'use strict';
var fs = require('fs'), path = require('path'), FFC = require('./ffc.js');

var file = process.argv[2] || path.join(__dirname, 'routes.json'), name = process.argv[3];
var cfg = JSON.parse(fs.readFileSync(file, 'utf8'));
var rt = cfg.routes.filter(function (r) { return r.name === name; })[0];
if (!rt || !rt.channel) { console.error('no route "' + name + '" with a channel in ' + file); process.exit(1); }
var cable = Object.assign({}, cfg.cable || {}, rt.cable || {});
var spec = { start: rt.start, target: rt.target, cable: cable, length: rt.length,
             obstacles: (cfg.obstacles || []).concat(rt.obstacles || []) };
var pr = FFC.problem(spec), t0 = Date.now();
var res = FFC.solve(pr, null, { enumerate: rt.enumerate });
var ok = res.ok && res.bendOk && res.clearOk;
console.log(name + (ok ? '' : '  ** NOT WITHIN THE LIMITS **') + ': free ' + res.L.toFixed(1) + ' mm, cable ' + res.total.toFixed(1) +
            ' mm end to end, R min ' + res.rMin.toFixed(2) + ', twist max ' + res.twistMax.toFixed(1) + ' deg/mm, smallest gap (film) ' +
            res.clearance.toFixed(2) + ' mm, energy ' + res.energy.toFixed(3) + ', ' + (Date.now() - t0) + ' ms');
if (!ok) process.exitCode = 1;

// the slot: the cable's path with the slot's width and thickness
var ch = rt.channel, prs = FFC.problem(Object.assign({}, spec, { cable: Object.assign({}, cable, { width: ch.width, thick: ch.thick }) }));
var m = FFC.mesh(prs, res.x, 4);
// outward faces for OpenSCAD: flip if the signed volume comes out negative
var vol = 0;
m.F.forEach(function (f) {
  var a = m.V[f[0]], b = m.V[f[1]], c = m.V[f[2]];
  vol += (a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0]) + a[2] * (b[0] * c[1] - b[1] * c[0])) / 6;
});
var faces = vol < 0 ? m.F : m.F.map(function (f) { return [f[0], f[2], f[1]]; });   // OpenSCAD: clockwise seen from outside
function n(v) { return +v.toFixed(4); }
var mod = name.replace(/[^A-Za-z0-9_]/g, '_');
var out = path.resolve(path.dirname(file), ch.out);
fs.writeFileSync(out,
  '// generated by cabling/channel.js from routes.json, route "' + name + '" -- do not edit\n' +
  '// slot ' + ch.width + ' x ' + ch.thick + ' mm along the FFC: free ' + res.L.toFixed(1) + ' mm, R min ' + res.rMin.toFixed(2) +
  ' mm, twist max ' + res.twistMax.toFixed(1) + ' deg/mm, smallest film-to-wall gap ' + res.clearance.toFixed(2) + ' mm\n' +
  'module ' + mod + '()\n  polyhedron(\n    points = [' + m.V.map(function (v) { return '[' + v.map(n).join(', ') + ']'; }).join(',\n      ') + '],\n' +
  '    faces = [' + faces.map(function (f) { return '[' + f.join(', ') + ']'; }).join(', ') + '],\n    convexity = 6);\n');
console.log('-> ' + path.relative(process.cwd(), out) + ': module ' + mod + '(), ' + m.V.length + ' points, ' + faces.length + ' faces, slot volume ' + Math.abs(vol).toFixed(1) + ' mm3');
