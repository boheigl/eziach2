#!/usr/bin/env python3
"""Writes <dir>/board.scad: the board as data for the cases, read back from KiCad:
outline, screw holes, keys, and every part's body as a box on the underside
(courtyard rectangle, height by package). Board frame as design.py: X, Y in the
board's plane, W out of its top face (0 on the top copper, the parts below
-hall_t). ../discant/ and ../bass/ include it.
usage: export_scad.py BOARD.kicad_pcb"""
import sys, os, pcbnew
import design as d

BOARD = sys.argv[1]
OX, OY = 150.0, 100.0
b = pcbnew.LoadBoard(BOARD)
def W(x, y): return (round(pcbnew.ToMM(x) - OX, 3), round(OY - pcbnew.ToMM(y), 3))
# body heights above the board's face [datasheet maxima; side-entry JST unverified]
# wire pads (PinHeader footprints, no header fitted): the wires come up from below, their
# stripped ends and the joints' fillets under the board taken as 1.0 [estimate]
HEIGHT = {"SOT-23": 1.12, "C_0402": 0.55, "R_0402": 0.55, "C_0805": 1.35, "WQFN-16": 0.8,
          "SOIC-16": 1.75, "L_0402": 0.55, "SM05B": 2.95, "BM05B": 4.25, "PinHeader": 1.0}
def height(fpid):
    for k, h in HEIGHT.items():
        if k in fpid: return h
    raise SystemExit("no height for " + fpid)

parts = []
for f in b.GetFootprints():
    side = "B" if f.GetLayer() == pcbnew.B_Cu else "F"
    cy = f.GetCourtyard(pcbnew.B_CrtYd if side == "B" else pcbnew.F_CrtYd)
    q = cy.BBox()
    x0, y1 = W(q.GetLeft(), q.GetTop()); x1, y0 = W(q.GetRight(), q.GetBottom())
    parts.append((f.GetReference(), side, x0, y0, x1, y1, height(f.GetFPIDAsString())))
parts.sort()
j1 = next(f for f in b.GetFootprints() if f.GetReference() == "J1")
pins = [p for p in j1.Pads() if p.GetNumber() in "12345"]
mp = [p for p in j1.Pads() if p.GetNumber() == "MP"]
cx = sum(W(p.GetPosition().x, p.GetPosition().y)[0] for p in pins) / len(pins)
# rows of wire pads (soldered wires, no connector): [ref, X of the row's middle, Y, X span]
wires = []
for f in sorted(b.GetFootprints(), key=lambda f: f.GetReference()):
    if "PinHeader" not in f.GetFPIDAsString(): continue
    xy = [W(p.GetPosition().x, p.GetPosition().y) for p in f.Pads()]
    xs = [q[0] for q in xy]
    wires.append([f.GetReference(), round((min(xs) + max(xs)) / 2, 3), round(sum(q[1] for q in xy) / len(xy), 3),
                  round(max(xs) - min(xs), 3)])

out = os.path.join(os.path.dirname(BOARD), "board.scad")
L = [f"// {d.TITLE}: generated by ../export_scad.py from {os.path.basename(BOARD)}; do not edit",
     "// board frame: X, Y in the board's plane, W out of its top face; parts hang below -hall_t",
     f"hall_t = {round(d.PCB_T + 0.07, 3)};   // laminate and both coppers",
     f"hall_tilt = atan({d.TAN});   // against each row's horizontal",
     f"hall_outline = {[list(map(lambda v: round(v, 3), p)) for p in d.OUTLINE]};",
     f"hall_corner_r = {d.CORNER_R};   // the outline's corners rounded (arcs tangent to both edges)",
     f"hall_holes = {[list(map(lambda v: round(v, 3), p)) for p in d.HOLES]};",
     f"hall_hole_d = {d.HOLE_D};",
     f"hall_keys = {[[k, h, round(d.key_xy(k, h)[0], 3), round(d.key_xy(k, h)[1], 3)] for k, h in d.KEYS]};   // row, key, X, Y",
     f"hall_sens_dy = {round(d.SENS_DY, 3)};",
     "// [ref, side, X0, Y0, X1, Y1, height]",
     "hall_parts = [", ",\n".join(f'  ["{r}", "{s}", {x0}, {y0}, {x1}, {y1}, {h}]' for r, s, x0, y0, x1, y1, h in parts), "];",
     f"hall_conn = [{round(cx, 3)}, {W(0, j1.GetPosition().y)[1]}];   // J1: the pins' middle (X), its centre (Y)",
     f"hall_conn_side = {'true' if 'Horizontal' in j1.GetFPIDAsString() else 'false'};   // side entry, opening to +Y",
     f"hall_conn_front = {round(max(W(p.GetPosition().x, p.GetPosition().y)[1] for p in mp) + 0.7, 3) if mp else 0};   // its opening (Y)",
     "hall_wires = " + str(wires).replace("'", '"') + ";   // wire pad rows: ref, X of the row's middle, Y, X span",
     ""]
open(out, "w").write("\n".join(L))
print(out, len(parts), "parts")
